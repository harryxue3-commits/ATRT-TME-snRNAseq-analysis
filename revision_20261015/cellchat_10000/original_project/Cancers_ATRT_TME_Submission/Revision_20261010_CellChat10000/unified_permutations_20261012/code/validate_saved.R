args<-commandArgs(trailingOnly=TRUE);out<-normalizePath(args[1])
suppressPackageStartupMessages(library(CellChat))
manifest<-read.csv(file.path(out,'tables/rerun_manifest.csv'),stringsAsFactors=FALSE);rows<-list()
for(i in seq_len(nrow(manifest))) {
 r<-manifest[i,];d<-file.path(out,'cellchat',r$run);o<-readRDS(file.path(d,'CellChat.rds'))
 x<-read.csv(file.path(d,'all_tested_interactions.csv'),stringsAsFactors=FALSE)
 z<-as.data.frame.table(o@net$prob,responseName='probability',stringsAsFactors=FALSE);names(z)[1:3]<-c('source','target','interaction_name')
 z$p_native<-as.vector(o@net$pval);z$p_finite<-as.vector(o@net$pval_finite);z$q_BH<-as.vector(o@net$qval_BH)
 a<-merge(z,x,by=c('source','target','interaction_name'),suffixes=c('_rds','_csv'))
 stopifnot(o@options$parameter$nboot==10000,nrow(a)==nrow(x),!anyDuplicated(paste(x$source,x$target,x$interaction_name)))
 for(k in c('probability','p_native','p_finite','q_BH'))stopifnot(max(abs(a[[paste0(k,'_rds')]]-a[[paste0(k,'_csv')]]))<1e-12)
 stopifnot(max(abs(as.vector(o@net$qval_BH)-p.adjust(as.vector(o@net$pval_finite),'BH')))<1e-12)
 if(r$scope=='external')stopifnot(all(table(o@idents)>=r$minimum))
 rows[[r$run]]<-data.frame(run=r$run,n_permutations=10000,n_tests=nrow(x),RDS_matches_CSV=TRUE,full_family_BH_reproduced=TRUE,inclusive_group_minimum_verified=TRUE)
 rm(o,x,z,a);gc()
}
all<-do.call(rbind,rows);write.csv(all,file.path(out,'tables/serialized_model_validation_10000.csv'),row.names=FALSE)
write.csv(all[grepl('^ALSF',all$run),],file.path(out,'tables/S18_serialized_model_validation.csv'),row.names=FALSE)
cat('Validated',nrow(all),'serialized models.\n')
