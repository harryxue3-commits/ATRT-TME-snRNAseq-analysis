args <- commandArgs(trailingOnly=TRUE)
project <- normalizePath(args[1])
rev <- file.path(project,'Cancers_ATRT_TME_Submission/Revision_20261010_CellChat10000')
out <- file.path(rev,'controlled_unannotated_20261012')
suppressPackageStartupMessages({library(CellChat);library(future)})
plan(sequential)
source(file.path(rev,'analysis/code/validated_fast_cellchat.R'))
fn <- make_fast_cellchat(file.path(rev,'analysis/code'))
obj <- readRDS(file.path(out,'models/MYC__plus_unannotated/prepared.rds'))
native <- CellChat::computeCommunProb(obj,type='truncatedMean',trim=.1,raw.use=TRUE,population.size=FALSE,nboot=37,seed.use=271828)
fast <- fn(obj,type='truncatedMean',trim=.1,raw.use=TRUE,population.size=FALSE,nboot=37,seed.use=271828)
stopifnot(identical(native@net$prob,fast@net$prob),identical(native@net$pval,fast@net$pval))
write.csv(data.frame(model='MYC__plus_unannotated',n_permutations=37,seed=271828,n_LR=nrow(obj@LR$LRsig),all_probabilities_identical=TRUE,all_pvalues_identical=TRUE),file.path(out,'tables/S13_controlled_acceleration_validation.csv'),row.names=FALSE)
message('New full-family native equivalence passed exactly')
